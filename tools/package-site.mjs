/* Turns the single-file app into a small website that installs like an app:
   a home-screen icon, full screen, working offline, and updating itself when
   a new version is uploaded. (D-076, UC-31)

     node tools/package-site.mjs <app.html> <icon-dir> <out-dir>

   Everything here is a pure function of its inputs except the CLI at the
   bottom, so the tests can check the site without a browser. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const SITE_NAME = "Sketchpad";
export const BACKGROUND = "#EDE7DA";
export const CACHE_PREFIX = "sketchpad-";
export const ICON_SIZES = [180, 192, 512];
export const iconName = (size) => `icon-${size}.png`;

/* The app as an installable thing: its name, its icon, and that it opens
   full screen at its own folder rather than wherever it was found. */
export function manifest() {
  return JSON.stringify({
    name: SITE_NAME,
    short_name: SITE_NAME,
    description: "Pick a key, play chords, practise lessons on the piano.",
    start_url: "./",
    scope: "./",
    display: "standalone",
    orientation: "any",
    background_color: BACKGROUND,
    theme_color: BACKGROUND,
    icons: ICON_SIZES.filter((s) => s !== 180).map((s) => ({ src: iconName(s), sizes: `${s}x${s}`, type: "image/png", purpose: "any" })),
  }, null, 2) + "\n";
}

/* iOS reads its own tags, not the manifest, for the home-screen icon and
   for opening without Safari's bars. */
export function headTags() {
  return [
    `<link rel="manifest" href="manifest.webmanifest">`,
    `<meta name="theme-color" content="${BACKGROUND}">`,
    `<meta name="apple-mobile-web-app-capable" content="yes">`,
    `<meta name="mobile-web-app-capable" content="yes">`,
    `<meta name="apple-mobile-web-app-title" content="${SITE_NAME}">`,
    `<meta name="apple-mobile-web-app-status-bar-style" content="default">`,
    `<link rel="apple-touch-icon" href="${iconName(180)}">`,
  ].join("");
}

/* Registration never throws into the app: if the browser refuses, the app
   still works online exactly as before. */
export const REGISTER = `<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("./sw.js").catch(()=>{}));</script>`;

export function installable(html) {
  if (!html.includes("</head>")) throw new Error("the page has no </head> to add the install tags to");
  if (!html.includes("</body>")) throw new Error("the page has no </body> to add the registration to");
  const i = html.indexOf("</head>");
  const withHead = html.slice(0, i) + headTags() + html.slice(i);
  const j = withHead.lastIndexOf("</body>");
  return withHead.slice(0, j) + REGISTER + withHead.slice(j);
}

/* The version is a fingerprint of everything the site ships, so any change
   to any file makes a new cache, and an unchanged upload keeps the old one. */
export function contentVersion(files) {
  const h = createHash("sha256");
  for (const name of Object.keys(files).sort()) { h.update(name); h.update("\0"); h.update(files[name]); h.update("\0"); }
  return h.digest("hex").slice(0, 12);
}

/* Cache first, from a cache named after the version. A new upload means a new
   sw.js, which the browser notices on the next open; it fetches the new files
   past any HTTP cache, switches over, and deletes the old cache. The page
   already open keeps running on what it loaded. */
export function serviceWorker(fileNames, version) {
  const files = ["./", ...fileNames.map((f) => "./" + f)];
  return `/* Sketchpad offline cache, generated by tools/package-site.mjs (D-076) */
const VERSION = ${JSON.stringify(CACHE_PREFIX + version)};
const FILES = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(VERSION)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: "reload" }))))
      .then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((k) => k.startsWith(${JSON.stringify(CACHE_PREFIX)}) && k !== VERSION)
        .map((k) => caches.delete(k))))
      .then(() => self.clients.claim()));
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  event.respondWith(
    caches.open(VERSION)
      .then((cache) => cache.match(event.request, { ignoreSearch: true }))
      .then((hit) => hit || fetch(event.request)));
});
`;
}

/* The whole site as { file name: contents }. */
export function packageSite(appHtml, icons) {
  const files = { "index.html": installable(appHtml), "manifest.webmanifest": manifest() };
  for (const size of ICON_SIZES) {
    const icon = icons[iconName(size)];
    if (!icon) throw new Error(`missing ${iconName(size)}`);
    files[iconName(size)] = icon;
  }
  const version = contentVersion(files);
  files["sw.js"] = serviceWorker(Object.keys(files).sort(), version);
  return { files, version };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [appPath, iconDir, outDir] = process.argv.slice(2);
  if (!outDir) { console.error("usage: node tools/package-site.mjs <app.html> <icon-dir> <out-dir>"); process.exit(1); }
  const icons = Object.fromEntries(readdirSync(iconDir).filter((f) => f.endsWith(".png")).map((f) => [f, readFileSync(join(iconDir, f))]));
  const { files, version } = packageSite(readFileSync(appPath, "utf8"), icons);
  mkdirSync(outDir, { recursive: true });
  for (const [name, body] of Object.entries(files)) writeFileSync(join(outDir, name), body);
  console.log(`site version ${version}: ${Object.keys(files).sort().join(", ")}`);
}
